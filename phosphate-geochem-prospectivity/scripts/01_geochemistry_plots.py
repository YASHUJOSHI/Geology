"""Geochemistry plots for a phosphorite dataset: P2O5 statistics, REE spider plots and
palaeoredox proxies.

Runs on SYNTHETIC demo data generated by ``phosprospect.synthetic``. To use your own
assays, replace ``load_assays()`` with a CSV reader; the column names it expects are
listed in ``phosprospect.synthetic.ANALYTES`` (majors in wt%, traces/REE in ppm).

    python scripts/01_geochemistry_plots.py
"""

import sys
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from phosprospect import build_features
from phosprospect.reference import CHONDRITE_REE_PPM, PAAS_REE_PPM, REE_ALL
from phosprospect.synthetic import make_basin

FIG = ROOT / "figures"
DATA = ROOT / "data"
LITH_ORDER = ["Phosphorite, pelletal", "Phosphatic carbonaceous shale",
              "Phosphatic limestone", "Carbonaceous shale", "Limestone"]
LITH_COLOUR = dict(zip(LITH_ORDER, ["#c0392b", "#e67e22", "#2e86c1", "#555555", "#8fbc8f"]))


def load_assays():
    df = make_basin()
    DATA.mkdir(exist_ok=True)
    df.to_csv(DATA / "synthetic_demo_assays.csv", index=False, float_format="%.4g")
    return df


def plain_ticks(ax):
    """Show 0.5, 1, 2 rather than 5x10^-1 on log axes."""
    fmt = matplotlib.ticker.FuncFormatter(lambda v, _: f"{v:g}")
    for axis in (ax.xaxis, ax.yaxis):
        if axis.get_scale() == "log":
            axis.set_major_formatter(fmt)
            axis.set_minor_formatter(matplotlib.ticker.NullFormatter())


def stamp(fig):
    for ax in fig.axes:
        plain_ticks(ax)
    fig.text(0.99, 0.01, "SYNTHETIC DEMO DATA - not real samples", ha="right",
             va="bottom", fontsize=7, color="grey", style="italic")


def p2o5_statistics(df):
    """Summary table by lithology plus histogram and log-probability plot."""
    stats = (df.groupby("lithology")["P2O5"]
               .describe(percentiles=[0.1, 0.5, 0.9])
               .reindex(LITH_ORDER).round(2))
    stats.to_csv(FIG / "p2o5_statistics_by_lithology.csv")
    print("P2O5 (wt%) by logged lithology\n", stats.to_string(), "\n")

    fig, (a1, a2) = plt.subplots(1, 2, figsize=(11, 4.2))
    bins = np.linspace(0, df["P2O5"].max() * 1.02, 40)
    for lith in LITH_ORDER:
        a1.hist(df.loc[df.lithology == lith, "P2O5"], bins=bins, alpha=0.7,
                label=lith, color=LITH_COLOUR[lith], stacked=False)
    for cut in (5, 15, 25):
        a1.axvline(cut, ls="--", lw=0.8, color="k")
    a1.set(xlabel="P2O5 (wt%)", ylabel="samples", title="P2O5 distribution by lithology")
    a1.legend(fontsize=7)

    # Log-probability plot: breaks in slope suggest mixed populations.
    v = np.sort(df["P2O5"].to_numpy())
    pct = (np.arange(1, v.size + 1) - 0.5) / v.size
    from scipy.stats import norm
    a2.plot(norm.ppf(pct), v, ".", ms=3, color="#333333")
    a2.set_yscale("log")
    ticks = [0.01, 0.1, 0.5, 0.9, 0.99]
    a2.set_xticks(norm.ppf(ticks), [f"{t*100:g}" for t in ticks])
    a2.set(xlabel="cumulative probability (%)", ylabel="P2O5 (wt%, log)",
           title="Log-probability plot")
    a2.grid(alpha=0.3)
    stamp(fig)
    fig.tight_layout()
    fig.savefig(FIG / "p2o5_statistics.png", dpi=150)
    plt.close(fig)


def ree_spider(df):
    """Median REE patterns per lithology, chondrite- and PAAS-normalised."""
    fig, axes = plt.subplots(1, 2, figsize=(12, 4.6))
    for ax, (ref, name) in zip(axes, [(CHONDRITE_REE_PPM, "CI chondrite (Sun & McDonough 1989)"),
                                      (PAAS_REE_PPM, "PAAS (Taylor & McLennan 1985)")]):
        norm_ = df[REE_ALL] / pd.Series(ref)
        x = np.arange(len(REE_ALL))
        for lith in LITH_ORDER:
            sub = norm_[df.lithology == lith]
            med = sub.median()
            lo, hi = sub.quantile(0.1), sub.quantile(0.9)
            ax.fill_between(x, lo, hi, color=LITH_COLOUR[lith], alpha=0.12)
            ax.plot(x, med, "-o", ms=3.5, color=LITH_COLOUR[lith], label=lith)
        ax.set_yscale("log")
        ax.set_xticks(x, REE_ALL)
        ax.set(ylabel="sample / reference", title=f"REE normalised to {name}")
        ax.grid(alpha=0.3, which="both")
    axes[0].legend(fontsize=7)
    axes[1].annotate("negative Ce anomaly\n(oxic seawater signal)", xy=(1, 1.3),
                     xytext=(2.5, 0.25), fontsize=7, arrowprops=dict(arrowstyle="->", lw=0.7))
    stamp(fig)
    fig.tight_layout()
    fig.savefig(FIG / "ree_spider_plots.png", dpi=150)
    plt.close(fig)


def redox_plots(df, f):
    """Palaeoredox cross-plots with literature threshold fields."""
    fig, axes = plt.subplots(1, 3, figsize=(15, 4.6))
    colours = df.lithology.map(LITH_COLOUR)

    # V/Cr vs Ni/Co, thresholds after Jones & Manning (1994).
    ax = axes[0]
    ax.scatter(f["V_Cr"], f["Ni_Co"], c=colours, s=8, alpha=0.6)
    for v in (2.0, 4.25):
        ax.axvline(v, ls="--", lw=0.8, color="k")
    for n in (5.0, 7.0):
        ax.axhline(n, ls="--", lw=0.8, color="k")
    ax.set(xscale="log", yscale="log", xlabel="V/Cr", ylabel="Ni/Co",
           title="V/Cr vs Ni/Co (Jones & Manning 1994)")
    ax.text(0.03, 0.95, "oxic", transform=ax.transAxes, fontsize=8, va="top")
    ax.text(0.97, 0.95, "anoxic", transform=ax.transAxes, fontsize=8, va="top", ha="right")

    # Authigenic U vs U/Th.
    ax = axes[1]
    ax.scatter(f["U_Th"], f["U_authigenic"], c=colours, s=8, alpha=0.6)
    for v in (0.75, 1.25):
        ax.axvline(v, ls="--", lw=0.8, color="k")
    ax.axhline(0, lw=0.8, color="k")
    ax.set(xscale="log", xlabel="U/Th", ylabel="authigenic U = U - Th/3 (ppm)",
           title="Uranium redox proxies (Wignall & Myers 1988)")

    # Ce anomaly vs Y/Ho: seawater-derived apatite plots low Ce/Ce*, high Y/Ho.
    ax = axes[2]
    ax.scatter(f["Y_Ho"], f["Ce_anomaly"], c=colours, s=8, alpha=0.6)
    ax.axvline(28, ls=":", lw=0.8, color="k")
    ax.axhline(1.0, ls=":", lw=0.8, color="k")
    ax.set(xlabel="Y/Ho", ylabel="Ce/Ce* (PAAS)", title="Ce anomaly vs Y/Ho")
    ax.text(0.97, 0.05, "seawater-like\nauthigenic apatite", transform=ax.transAxes,
            fontsize=8, ha="right")
    ax.text(0.03, 0.95, "detrital /\nchondritic Y/Ho", transform=ax.transAxes,
            fontsize=8, va="top")

    handles = [plt.Line2D([], [], marker="o", ls="", color=c, label=l)
               for l, c in LITH_COLOUR.items()]
    axes[0].legend(handles=handles, fontsize=7, loc="lower right")
    stamp(fig)
    fig.tight_layout()
    fig.savefig(FIG / "palaeoredox_proxies.png", dpi=150)
    plt.close(fig)


def main():
    FIG.mkdir(exist_ok=True)
    df = load_assays()
    f = build_features(df)
    p2o5_statistics(df)
    ree_spider(df)
    redox_plots(df, f)
    print("Figures written to", FIG)


if __name__ == "__main__":
    main()
